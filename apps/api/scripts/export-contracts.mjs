/**
 * Exports typed API contracts + a minimal fetch client for the Next frontend.
 * Source of truth: apps/api OpenAPI + Zod schemas + domain/rbac-catalog.ts.
 *
 * Usage (from apps/api):
 *   npm run export:contracts
 *
 * Writes (deterministic):
 *   ../../src/lib/api/generated/{types,client,index}.ts
 *   ../../src/lib/api/contracts/v1-employees.ts  (compat re-export)
 *
 * Catalog loader: isolated parse of rbac-catalog.ts frozen arrays (no AST).
 * Residual: Node cannot import .ts without tsx IPC; parser is tested for
 * exact parity with runtime ROLES/PERMISSIONS. Prefer switching to a JSON
 * artifact later if the parser becomes fragile.
 */
