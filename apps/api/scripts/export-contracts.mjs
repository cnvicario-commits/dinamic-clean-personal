/**
 * Isolated catalog loader — parses only `export const NAME = Object.freeze([...] as const)`.
 * Does not scan rbac.ts grants; ignores // line comments.
 */
export function loadRbacCatalogFromSource(src) {
  const withoutLineComments = src
    .split('\n')
    .map((line) => {
      const idx = line.indexOf('//')
      return idx >= 0 ? line.slice(0, idx) : line
    })
    .join('\n')

  function extractFrozenStringArray(constName) {
    const re = new RegExp(
      `export const ${constName} = Object\\.freeze\\(\\[([\\s\\S]*?)\\] as const\\)`,
    )
    const m = withoutLineComments.match(re)
    if (!m) throw new Error(`Could not parse ${constName} from rbac-catalog.ts`)
    const values = [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
    if (values.length === 0) {
      throw new Error(`${constName} parsed empty — check rbac-catalog.ts format`)
    }
    return values
  }

  return {
    roles: extractFrozenStringArray('ROLES'),
    permissions: extractFrozenStringArray('PERMISSIONS'),
  }
}

function loadRbacCatalogs() {
  const src = readFileSync(catalogPath, 'utf8')
  return loadRbacCatalogFromSource(src)
}

function asUnion(values) {
  return values.map((v) => `  | '${v}'`).join('\n')
}

function asConstArray(name, values) {
  const body = values.map((v) => `  '${v}',`).join('\n')
  return `export const ${name} = [\n${body}\n] as const`
}

function writeStable(path, contents) {
  mkdirSync(dirname(path), { recursive: true })
  const normalized = contents.replace(/\r\n/g, '\n').replace(/\n*$/, '\n')
  writeFileSync(path, normalized, 'utf8')
  console.info(`Wrote ${path}`)
}

const TYPE_LINE_WIDTH = 100

function matchingCloser(src, openIndex, open, close) {
  let depth = 0
  let quote = false
  for (let i = openIndex; i < src.length; i++) {
    const c = src[i]
    if (quote) {
      if (c === '\\') {
        i += 1
        continue
      }
      if (c === "'") quote = false
      continue
    }
    if (c === "'") {
      quote = true
      continue
    }
    if (c === open) depth += 1
    else if (c === close) {
      depth -= 1
      if (depth === 0) return i
    }
  }
  return -1
}

function splitTopLevel(src, separator) {
  const parts = []
  let start = 0
  let braces = 0
  let angles = 0
  let parens = 0
  let quote = false
  for (let i = 0; i < src.length; i++) {
    const c = src[i]
    if (quote) {
      if (c === '\\') {
        i += 1
        continue
      }
      if (c === "'") quote = false
      continue
    }
    if (c === "'") {
      quote = true
      continue
    }
    if (c === '{') braces += 1
    else if (c === '}') braces -= 1
    else if (c === '<') angles += 1
    else if (c === '>') angles -= 1
    else if (c === '(') parens += 1
    else if (c === ')') parens -= 1
    else if (c === separator && braces === 0 && angles === 0 && parens === 0) {
      parts.push(src.slice(start, i))
      start = i + 1
    }
  }
  parts.push(src.slice(start))
  return parts
}

function prettifyInline(src) {
  let out = ''
  let quote = false
  for (let i = 0; i < src.length; i++) {
    const c = src[i]
    if (quote) {
      out += c
      if (c === '\\') {
        out += src[i + 1] ?? ''
        i += 1
        continue
      }
      if (c === "'") quote = false
      continue
    }
    if (c === "'") {
      quote = true
      out += c
      continue
    }
    if (c === '|' || c === '&') {
      if (!out.endsWith(' ')) out += ' '
      out += `${c} `
      continue
    }
    if (c === ':') {
      out += ': '
      continue
    }
    if (c === ',') {
      out += ', '
      continue
    }
    if (c === ';') {
      out += '; '
      continue
    }
    if (c === '{') {
      out += '{ '
      continue
    }
    if (c === '}') {
      if (out.endsWith(' ')) out = out.slice(0, -1)
      out += ' }'
      continue
    }
    if (c === ' ' && out.endsWith(' ')) continue
    out += c
  }
  return out.replace(/ +/g, ' ').replace(/\{ \}/g, '{}').trim()
}

function formatPropInline(prop) {
  const colon = topLevelColon(prop)
  if (colon < 0) return prettifyInline(prop)
  const key = prop.slice(0, colon).trim()
  const type = prop.slice(colon + 1).trim()
  return `${key}: ${prettifyInline(type)}`
}

function topLevelColon(prop) {
  const parts = splitTopLevel(prop, ':')
  if (parts.length < 2) return -1
  return parts[0].length
}

function formatObject(inner, indent, prefixWidth) {
  const props = splitTopLevel(inner, ';').map((part) => part.trim()).filter(Boolean)
  if (props.length === 0) return '{}'
  const inline = `{ ${props.map((prop) => formatPropInline(prop)).join('; ')} }`
  if (prefixWidth + inline.length <= TYPE_LINE_WIDTH) return inline
  const pad = '  '.repeat(indent)
  const innerPad = '  '.repeat(indent + 1)
  const lines = props.map((prop) => `${innerPad}${formatProp(prop, indent + 1)}`)
  return `{\n${lines.join('\n')}\n${pad}}`
}

function formatProp(prop, indent) {
  const colon = topLevelColon(prop)
  if (colon < 0) return formatExpr(prop, indent, indent * 2)
  const key = prop.slice(0, colon).trim()
  const type = prop.slice(colon + 1).trim()
  const head = `${key}: `
  return head + formatExpr(type, indent, indent * 2 + head.length)
}

function formatExpr(src, indent, initialWidth) {
  let out = ''
  let quote = false
  const widthBefore = () => {
    const nl = out.lastIndexOf('\n')
    if (nl >= 0) return out.length - nl - 1
    return initialWidth + out.length
  }
  for (let i = 0; i < src.length; i++) {
    const c = src[i]
    if (quote) {
      out += c
      if (c === '\\') {
        out += src[i + 1] ?? ''
        i += 1
        continue
      }
      if (c === "'") quote = false
      continue
    }
    if (c === "'") {
      quote = true
      out += c
      continue
    }
    if (c === '{') {
      const end = matchingCloser(src, i, '{', '}')
      if (end < 0) {
        out += c
        continue
      }
      let extra = 0
      let j = end + 1
      while (src[j] === '[' || src[j] === ']') {
        extra += 1
        j += 1
      }
      out += formatObject(src.slice(i + 1, end), indent, widthBefore() + extra)
      i = end
      continue
    }
    if (c === '|' || c === '&') {
      if (!out.endsWith(' ') && !out.endsWith('\n')) out += ' '
      out += `${c} `
      continue
    }
    if (c === ',') {
      out += ', '
      continue
    }
    if (c === ' ' && (out.endsWith(' ') || out.endsWith('\n'))) continue
    out += c
  }
  return out.trim()
}

function wrapLongTypeLines(source) {
  const out = []
  for (const line of source.split('\n')) {
    if (line.length <= TYPE_LINE_WIDTH) {
      out.push(line)
      continue
    }
    const indent = line.match(/^\s*/)[0]
    const trimmed = line.trim()
    if (trimmed.startsWith('export type ') && trimmed.includes(' = ')) {
      const eq = trimmed.indexOf(' = ')
      const name = trimmed.slice('export type '.length, eq)
      const body = trimmed.slice(eq + 3)
      const prefix = `export type ${name} = `
      out.push(...(prefix + formatExpr(body, 0, prefix.length)).split('\n'))
      continue
    }
    if (trimmed.includes('{')) {
      const level = Math.floor(indent.length / 2)
      const parts = formatProp(trimmed, level).split('\n')
      out.push(indent + parts[0])
      out.push(...parts.slice(1))
      continue
    }
    out.push(line)
  }
  return out.join('\n')
}

